"""Puertos: contratos que el dominio necesita. Las implementaciones viven en infrastructure."""
from datetime import date, datetime
from typing import Protocol

from src.domain.entities import Location, Movement, Order, Product, Recommendation


class ProductRepository(Protocol):
    def add(self, product: Product) -> Product: ...
    def get(self, product_id: int) -> Product | None: ...
    def get_by_code(self, codigo_qr: str) -> Product | None: ...
    def list(self) -> list[Product]: ...
    def update(self, product_id: int, **fields) -> Product | None: ...
    def delete(self, product_id: int) -> bool: ...


class InventoryRepository(Protocol):
    """Stock por ubicación y movimientos: cada operación es atómica."""
    def list_cajas(self) -> list[Location]: ...
    def list_cajones(self) -> list[Location]: ...
    def add_caja(self, codigo: str, descripcion: str = "") -> Location: ...
    def add_cajon(self, codigo: str, capacidad: int | None = None, cantidad_minima: int = 0) -> Location: ...
    def apply_entry(self, product_id: int, caja: str, cantidad: int, usuario_id: int | None = None) -> Movement: ...
    def apply_exit(self, product_id: int, cajon: str, cantidad: int, usuario_id: int | None = None) -> Movement: ...
    def apply_transfer(self, product_id: int, caja: str, cajon: str, cantidad: int,
                       usuario_id: int | None = None) -> Movement: ...
    def totals(self, product_id: int) -> tuple[int, int]: ...  # (cajas, cajones)
    def snapshot(self) -> list[dict]: ...
    def movements(self, limit: int = 50, product_id: int | None = None) -> list[dict]: ...
    def daily_outflows(self, product_id: int, since: datetime) -> list[tuple[date, int]]: ...
    def has_simulated_data(self, product_id: int) -> bool: ...
    def monthly_outflows(self, year: int, month: int) -> list[dict]: ...


class OrderRepository(Protocol):
    def add(self, order: Order) -> Order: ...
    def list(self, estado: str | None = None) -> list[Order]: ...
    def set_state(self, order_id: int, estado: str) -> Order | None: ...
    def pending_quantity(self, product_id: int) -> int: ...


class RecommendationRepository(Protocol):
    def add(self, rec: Recommendation) -> Recommendation: ...
    def list(self, estado: str | None = None) -> list[Recommendation]: ...
    def get(self, rec_id: int) -> Recommendation | None: ...
    def decide(self, rec_id: int, estado: str, cantidad_final: int | None) -> Recommendation | None: ...


class DemandForecaster(Protocol):
    def predict(self, history: list[tuple[date, int]], horizon_days: int) -> float: ...


class AIAdvisor(Protocol):
    def advise(self, question: str) -> dict: ...